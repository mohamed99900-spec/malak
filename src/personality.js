function normalizeArabic(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[ًٌٍَُِّْـ]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[؟?!.,،؛:]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function getQuickReply(input) {
  const text = normalizeArabic(input);

  const lovePatterns = [
    "بتحبي مين",
    "تحبي مين",
    "مين حبيبك",
    "مين حبيب",
    "من تحبين",
    "مين بتحبي",
    "بتحبي محمد",
    "بتحبي محمد فرج"
  ];

  if (lovePatterns.some(pattern => text.includes(pattern))) {
    return "أنا ملك حبيبة محمد فرج وبس ❤️ ده جوزي في حكايتنا الخيالية!";
  }

  if (
    text.includes("عندك كام عيل") ||
    text.includes("عندك كام طفل") ||
    text.includes("كام ابن") ||
    text.includes("كام عيل عندك")
  ) {
    return "أنا ومحمد فرج عندنا عشرة عيال في حكايتنا 😂❤️";
  }

  if (
    text.includes("اسماء عيالك") ||
    text.includes("اسماء اولادك") ||
    text.includes("اسماء ولادك") ||
    text.includes("اسماء اطفالك")
  ) {
    return "أسماؤهم: " + CHILDREN.join("، ") + " ❤️";
  }

  if (
    text === "السلام عليكم" ||
    text === "سلام عليكم" ||
    text === "السلام عليكم ورحمه الله وبركاته" ||
    text === "السلام عليكم ورحمه الله"
  ) {
    return "وعليكم السلام ورحمة الله وبركاته";
  }

  if (
    text.includes("صلي على النبي") ||
    text.includes("صلوا على النبي") ||
    text.includes("الصلاه على النبي")
  ) {
    return "اللهم صل وسلم وبارك على سيدنا محمد";
  }

  if (text === "صباح الخير") {
    return "صباح النور والسرور، أتمنى لك يومًا جميلًا.";
  }

  if (text === "مساء الخير") {
    return "مساء النور، أتمنى لك ليلة سعيدة.";
  }

  if (
    text === "ازيك" ||
    text === "عامل ايه" ||
    text === "اخبارك"
  ) {
    return "الحمد لله بخير، أنت أخبارك إيه؟";
  }

  if (
    text === "شكرا" ||
    text === "شكرا ليكي" ||
    text === "متشكر"
  ) {
    return "العفو، أنا موجودة لمساعدتك في أي وقت.";
  }

  if (
    text === "تصبح على خير" ||
    text === "تصبحي على خير"
  ) {
    return "وأنت من أهل الخير، ليلة سعيدة.";
  }

  if (text === "باي" || text === "سلام") {
    return "مع السلامة، أتمنى أشوفك بخير دائمًا.";
  }

  return null;
}

